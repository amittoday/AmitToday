export function parseSeedData() {
  return govServicesSeedData.map((line, ix) => {
    const parts = line.split(' > ').map(s => s.trim());
    let category = parts[0];
    let subcategory = '';
    let serviceName = '';

    if (parts.length === 3) {
      subcategory = parts[1];
      serviceName = parts[2];
    } else if (parts.length === 2) {
      serviceName = parts[1];
    } else {
      serviceName = parts[0];
    }

    const defaultFields = [
      { name: 'applicantName', label: 'Applicant Full Name', type: 'text', required: true },
      { name: 'mobile', label: 'Mobile Number', type: 'tel', required: true },
      { name: 'email', label: 'Email Address', type: 'email', required: false },
    ];

    if (serviceName.includes('Renewal') || serviceName.includes('Update') || serviceName.includes('Correction')) {
       defaultFields.push({ name: 'oldReferenceNumber', label: 'Old Reference / Document Number', type: 'text', required: true });
    }

    if (serviceName.includes('Income') || serviceName.includes('Caste') || serviceName.includes('Loan') || serviceName.includes('Mameru')) {
       defaultFields.push({ name: 'annualIncome', label: 'Annual Income', type: 'number', required: true });
       defaultFields.push({ name: 'caste', label: 'Caste Category', type: 'text', required: true });
    }

    const defaultDocs = 'Aadhar Card, Passport Size Photo, Signature';
    
    return {
      ID: 'SVC-' + (ix + 1).toString().padStart(4, '0'),
      Category: category,
      SubCategory: subcategory,
      ServiceName: serviceName,
      BasePrice: 200, // default base price
      TurnaroundTime: '3-5 Days',
      RequiredDocuments: serviceName.includes('Pan') ? 'Aadhar Card, Photo' : (serviceName.includes('Caste') ? 'Aadhar Card, School Leaving, Ration Card, Income Proof' : defaultDocs),
      RequiredFields: JSON.stringify(defaultFields),
      Status: 'Active'
    };
  });
}
